import { test, expect } from '@playwright/test';

test('real anatomy supports depth, relief, distortion, pinned identity, and PNG provenance', async ({ page }) => {
  test.setTimeout(180000);
  const paint = () => page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  const errors: string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:900});
  await page.goto('/demo/index.html?scenario=anatomy&mode=flatmap');
  const status=page.locator('[data-linked-flatmap-status]');await expect(status).toContainText('Ready:',{timeout:60000});
  await paint();
  await page.screenshot({path:test.info().outputPath('map-desktop.png')});
  await page.locator('#qf-vertex').fill('86934');await page.locator('#qf-pin').click();
  await expect(status).toContainText('Selected vertex 86934');
  const scalar=await page.locator('#qf-pinned').innerText();
  await page.locator('#qf-mode').getByRole('radio',{name:'Relief',exact:true}).check();
  await page.locator('#qf-exaggeration').fill('3');
  await expect(page.locator('#qf-pinned')).toHaveText(scalar);
  await expect(page.locator('.anat-cell-label').nth(1)).toHaveText('Relief · display only');
  await page.locator('#qf-mode').scrollIntoViewIfNeeded();
  await paint();
  await page.screenshot({path:test.info().outputPath('relief-desktop.png')});
  await page.locator('#qf-mode').getByRole('radio',{name:'Map',exact:true}).check();
  await page.locator('#qf-source').getByRole('radio',{name:'Volume',exact:true}).check();
  await expect(status).toContainText('Ready:',{timeout:60000});
  await page.locator('#qf-depth').fill('0.8');
  await expect(status).toContainText('Ready:',{timeout:60000});
  await expect(page.locator('#qf-pinned')).not.toHaveText(scalar);
  await expect(page.locator('.film-corner-br')).toContainText('86934');
  await paint();
  await page.screenshot({path:test.info().outputPath('volume-desktop.png')});
  await page.locator('#qf-mode').getByRole('radio',{name:'Distortion',exact:true}).check();
  await expect(status).toContainText('Ready:',{timeout:60000});
  await expect(page.locator('.anat-quant-legend')).toContainText('log₂ relative area');
  await paint();
  await page.screenshot({path:test.info().outputPath('distortion-desktop.png')});
  await page.locator('#qf-mode').getByRole('radio',{name:'Map',exact:true}).check();
  await expect(status).toContainText('Ready:',{timeout:60000});
  await page.getByText('Resolution, export and provenance',{exact:true}).click();
  await page.locator('#qf-export').click();
  await expect(page.locator('#qf-export-status')).toContainText('Ready',{timeout:90000});
  const png=page.getByRole('link',{name:'Save flatmap.png'}),json=page.getByRole('link',{name:'Save flatmap.json'});
  const artifact=await page.evaluate(async ([pngUrl,jsonUrl])=>{
    const blob=await(await fetch(pngUrl!)).blob(),bitmap=await createImageBitmap(blob),metadata=await(await fetch(jsonUrl!)).json();
    const dimensions=[bitmap.width,bitmap.height];bitmap.close();return {dimensions,metadata,bytes:blob.size};
  },[await png.getAttribute('href'),await json.getAttribute('href')]);
  expect(artifact.dimensions[0]).toBe(1024);expect(artifact.bytes).toBeGreaterThan(10000);
  expect(artifact.metadata.schema).toBe('surfview.quantitative-flatmap.v1');expect(artifact.metadata.presentation.relief).toBe(false);
  expect(artifact.metadata.source.kind).toBe('volume-scalar');expect(artifact.metadata.provenance.assetSha256).toMatch(/^[a-f0-9]{64}$/);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  await paint();
  await page.screenshot({path:test.info().outputPath('map-narrow.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  const caption = await page.locator('.anat-cell-label').nth(1).boundingBox();
  const legend = await page.locator('.anat-quant-legend').boundingBox();
  const pinned = await page.locator('.film-corner-br').boundingBox();
  expect(legend!.y + legend!.height).toBeLessThan(caption!.y);
  expect(caption!.y + caption!.height).toBeLessThan(pinned!.y);
  await page.locator('#qf-mode').getByRole('radio',{name:'Relief',exact:true}).check();
  await expect(page.locator('#qf-exaggeration')).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await paint();
  await page.screenshot({path:test.info().outputPath('relief-narrow.png'),fullPage:true});
  await page.locator('#anatomy-mode').getByRole('radio',{name:'Views',exact:true}).check();
  await expect(page.locator('#viewer-slot canvas')).toHaveCount(1,{timeout:30000});
  expect(errors).toEqual([]);
});
